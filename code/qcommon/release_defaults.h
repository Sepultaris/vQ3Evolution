static const char *VQ3E_DefaultValue(const char *name, const char *fallback) {
#ifndef DEDICATED
    int low=0, high=(int)(sizeof(vq3eReleaseDefaults)/sizeof(vq3eReleaseDefaults[0]))-1;
    while (low<=high) {
        int middle=low+(high-low)/2;
        int order=Q_stricmp(name,vq3eReleaseDefaults[middle].name);
        if (!order) return vq3eReleaseDefaults[middle].value;
        if (order<0) high=middle-1; else low=middle+1;
    }
#else
    (void)name;
#endif
    return fallback;
}
#endif
